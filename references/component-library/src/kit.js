/* 外观：system 跟随系统（默认）、light、dark。写在 <html> 上：类 light / dark 加同名的 data-theme；system 时两者都去掉。
 * 任意祖先带类 dark（或 light）都生效，不一定是 <html>，所以原型可以只给自己的舞台容器加类。选择记在本机（localStorage 的 luz-theme，读写包 try）。 */
const APPEARANCES = [['system', '跟随系统'], ['light', '浅色'], ['dark', '深色']]
const APPEARANCE_KEY = 'luz-theme'
function getAppearance() {
  const h = document.documentElement
  return h.classList.contains('dark') || h.dataset.theme === 'dark' ? 'dark' : h.classList.contains('light') || h.dataset.theme === 'light' ? 'light' : 'system'
}
function setAppearance(mode, persist = true) {
  mode = mode === 'dark' || mode === 'light' ? mode : 'system'
  const h = document.documentElement
  h.classList.remove('dark', 'light'); h.removeAttribute('data-theme')
  if (mode !== 'system') { h.classList.add(mode); h.setAttribute('data-theme', mode) }
  if (persist) { try { mode === 'system' ? localStorage.removeItem(APPEARANCE_KEY) : localStorage.setItem(APPEARANCE_KEY, mode) } catch (e) {} }
  document.dispatchEvent(new CustomEvent('appearancechange', { detail: { mode } }))
  return mode
}
