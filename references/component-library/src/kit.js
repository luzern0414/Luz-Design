const hex2 = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
const mixc = (a, b, t) => '#' + hex2(a).map((v, i) => Math.round(v * t + hex2(b)[i] * (1 - t)).toString(16).padStart(2, '0')).join('')
/* 主题色变量。浅色：--p 主色（白字 ≥4.5:1）--pd 深一阶 --pt 极浅底 --pm 浅底边 --ga --gb 渐变两端 --p-rgb；加 --p-text（文字用色，浅色 = --pd）和 --p-fg（--p 当文字用，浅色 = --p）。
 * 第二个参数 'dark' 给出深色那一组（DARK_THEMES）。页面上不要把它们写成行内样式：那样会压住深色，请用 applyTheme。 */
function themeVars(id, scheme = 'light') {
  const t = THEMES.find((x) => x.id === id) || THEMES[0]
  if (scheme === 'dark') {
    const d = DARK_THEMES[t.id]
    return { '--p': d.p, '--pd': d.pd, '--pt': d.pt, '--pm': d.pm, '--ga': mixc(d.p, '#FFFFFF', 0.95), '--gb': d.p, '--p-rgb': hex2(d.p).join(','), '--p-text': d.text, '--p-fg': d.text }
  }
  return { '--p': t.p, '--pd': t.pd, '--pt': t.pt, '--pm': t.pm, '--ga': mixc(t.p, '#FFFFFF', 0.95), '--gb': t.p, '--p-rgb': hex2(t.p).join(','), '--p-text': t.pd, '--p-fg': t.p }
}
